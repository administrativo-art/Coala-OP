import { expect, test } from '@playwright/test';
import { getApps, initializeApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { assertFirestoreEmulatorSafety } from '../../helpers/firestore-emulator-safety.mjs';
import { E2E_USER } from '../support/global-setup';

test.use({ actionTimeout: 30_000 });

test('registra serviço realizado e conclui ocorrência existente com peças sem duplicar histórico', async ({ page }) => {
  test.setTimeout(300_000);
  assertFirestoreEmulatorSafety({ projectId: 'demo-coala-e2e' });
  const app = getApps().find(app => app.name === 'asset-maintenance-e2e')
    ?? initializeApp({ projectId: 'demo-coala-e2e' }, 'asset-maintenance-e2e');
  const db = getFirestore(app, 'coala');
  const assetId = 'asset-maintenance-e2e';
  const now = new Date().toISOString();
  await db.collection('assets').doc(assetId).set({ workspaceId: 'coala', code: 'PAT-990912', name: 'Motor manutenção E2E', category: 'Patrimônio', subcategory: 'Equipamentos', status: 'ativo', currentKioskId: 'e2e-kiosk', currentKioskName: 'Quiosque E2E', sourceType: 'manual', lifecycleVersion: 1, createdAt: now, updatedAt: now });
  await db.collection('assetMaintenanceOccurrences').doc('asset-existing-e2e').set({ workspaceId: 'coala', assetId, type: 'corrective', status: 'open', version: 1, dueDate: '2026-01-01', description: 'Ajuste pendente E2E', createdBy: { userId: 'opening-actor', namespace: 'main.users', nameSnapshot: 'Quem abriu' }, assignee: { type: 'user', id: E2E_USER.uid, namespace: 'main.users', nameSnapshot: 'Administrador E2E' }, createdAt: now, updatedAt: now });
  const taskCount = (await db.collection('tasks').get()).size;
  const documentCount = (await db.collection('generatedDocuments').get()).size;
  await page.goto('/login');
  await page.getByLabel('E-mail').fill(E2E_USER.email);
  await page.getByLabel('Senha').fill(E2E_USER.password);
  await page.getByRole('button', { name: 'Entrar no sistema' }).click();
  await expect(page).toHaveURL(/\/dashboard(?:$|\/)/, { timeout: 180_000 });
  await page.goto('/dashboard/assets');
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Motor manutenção E2E', exact: true }) }).click();
  await page.getByRole('button', { name: /Auditoria e manutenção/ }).click();
  await page.getByRole('button', { name: 'Nova manutenção', exact: true }).click();
  const modal = page.getByRole('dialog', { name: 'Nova manutenção', exact: true });
  await modal.getByRole('radio', { name: 'Registrar manutenção realizada', exact: true }).click();
  await expect(modal.getByLabel('Concluir até')).toHaveCount(0);
  await modal.getByLabel('Data da realização').fill('2026-01-02');
  await modal.getByLabel('Serviço realizado').fill('Troca de rolamento E2E');
  await modal.getByLabel('Peças substituídas (opcional)').fill('1 rolamento\n2 retentores');
  const createdPromise = page.waitForResponse(response => response.url().endsWith(`/api/assets/${assetId}/maintenance-occurrences`) && response.request().method() === 'POST');
  await modal.getByRole('button', { name: 'Registrar realização', exact: true }).click();
  const created = await createdPromise;
  expect(created.status()).toBe(201);
  const authHeaders = await created.request().allHeaders();
  await expect(modal).toBeHidden();
  const occurrences = await db.collection('assetMaintenanceOccurrences').where('assetId', '==', assetId).get();
  const completed = occurrences.docs.find(doc => doc.get('description') === 'Troca de rolamento E2E')!;
  expect(completed.get('status')).toBe('completed');
  expect(completed.get('performedOn')).toBe('2026-01-02');
  expect(completed.get('components')).toEqual(['1 rolamento', '2 retentores']);
  expect(completed.get('taskId')).toBeUndefined();
  expect(completed.get('orderDocumentId')).toBeUndefined();
  expect(completed.get('provisioningStatus')).toBeUndefined();
  expect((await db.collection('tasks').get()).size).toBe(taskCount);
  expect((await db.collection('generatedDocuments').get()).size).toBe(documentCount);
  for (const source of ['asset-maintenance-creators', 'asset-maintenance-completers', 'asset-maintenance-assignees']) {
    const response = await page.request.get(`/api/privacy/person-inventory?namespace=main.users&id=${E2E_USER.uid}&source=${source}`, { headers: { Authorization: authHeaders.authorization } });
    expect(response.status()).toBe(200);
    expect((await response.json()).items.some((item: { id: string }) => item.id === completed.id)).toBe(true);
  }
  await page.getByRole('button', { name: 'Registrar realização', exact: true }).click();
  const finish = page.getByRole('dialog', { name: 'Registrar realização', exact: true });
  await finish.getByLabel('Data da realização').fill('2026-01-03');
  await finish.getByLabel('Serviço realizado').fill('Ajuste concluído E2E');
  await finish.getByLabel('Peças substituídas (opcional)').fill('1 correia');
  await finish.getByRole('button', { name: 'Registrar realização', exact: true }).click();
  await expect(finish).toBeHidden();
  const existing = await db.collection('assetMaintenanceOccurrences').doc('asset-existing-e2e').get();
  expect(existing.get('version')).toBe(2);
  expect(existing.get('status')).toBe('completed');
  expect(existing.get('createdBy.userId')).toBe('opening-actor');
  expect(existing.get('completedBy.userId')).toBe(E2E_USER.uid);
  expect(existing.get('components')).toEqual(['1 correia']);
  const linked = db.batch();
  linked.update(existing.ref, { orderDocumentId: 'order-maintenance-e2e', orderProtocol: 'MNT-E2E' });
  linked.set(db.collection('generatedDocuments').doc('order-maintenance-e2e'), { workspaceId: 'coala', sourceAssetId: assetId, sourceMaintenanceOccurrenceId: existing.id, protocol: 'MNT-E2E', pdfStoragePath: 'demo/maintenance-e2e.pdf', createdAt: now });
  linked.set(db.collection('assetMovements').doc('order-movement-e2e'), { workspaceId: 'coala', assetId, type: 'MANUTENCAO_ORDEM', source: { type: 'maintenance', id: existing.id }, occurredAt: now });
  linked.set(db.collection('assetMovements').doc('independent-edit-e2e'), { workspaceId: 'coala', assetId, type: 'EDICAO', notes: 'Edição independente E2E', occurredAt: now });
  await linked.commit();
  const history = await page.request.get(`/api/assets/${assetId}/history?limit=30`, { headers: { Authorization: authHeaders.authorization } });
  expect(history.status()).toBe(200);
  const historyRows = (await history.json()).items as Array<{ id: string; source: string }>;
  expect(historyRows.filter(item => item.source === 'maintenance')).toHaveLength(2);
  expect(historyRows.map(item => item.id)).toContain('independent-edit-e2e');
  expect(historyRows.map(item => item.id)).not.toContain('order-movement-e2e');
  expect(historyRows.map(item => item.id)).not.toContain('order-maintenance-e2e');
  await page.getByRole('button', { name: /Histórico geral/ }).click();
  await expect(page.getByText('Troca de rolamento E2E', { exact: true })).toBeVisible();
  await expect(page.getByText('Ajuste concluído E2E', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Motor manutenção E2E', exact: true })).toBeVisible();
  expect((await db.collection('assetMovements').where('assetId', '==', assetId).get()).size).toBe(2);
});
